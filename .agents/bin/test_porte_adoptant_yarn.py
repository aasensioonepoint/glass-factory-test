class MutantsYarnTests(_BancYarn):
    """Les mutants yarn, rejoués à chaque passage : le scénario tourne sur la
    source PUIS sur la copie mutée (`muter` du banc principal, attribut de
    module : aucune classe de tests importée par son nom). V-TABLE reste dans
    le banc principal."""

    muter = banc.MutantsDurablesTests.muter

    def jouer(self, contenu: str, porte: Path, **env: str) -> tuple[int, str]:
        rc, sortie, _res = self.lancer(self.arbre_yarn(contenu), porte=porte, **env)
        return rc, sortie

    def test_V_YARN_DEFAUT(self):
        mutant = self.muter('    ("yarn.lock", "yarn", ("install", "--frozen-lockfile")),\n',
                            '    ("yarn.lock", "yarn", ("install", "--immutable")),\n')
        for porte, attendu in ((banc.PORTE, FROZEN), (mutant, IMMUTABLE)):
            rc, sortie = self.jouer("x\n", porte)
            self.assertEqual(rc, 0, sortie)
            self.assertEqual(self.argv_yarn()[0], attendu, sortie)

    def test_V_YARN1(self):
        mutant = self.muter('return defaut, "Yarn 1"', 'return ("install", "--immutable"), "Yarn 1"')
        for porte, attendu in ((banc.PORTE, FROZEN), (mutant, IMMUTABLE)):
            rc, sortie = self.jouer(ENTETE_V1, porte)
            self.assertEqual(rc, 0, sortie)
            self.assertEqual(self.argv_yarn()[0], attendu, sortie)

    def test_V_PRIO(self):
        mutant = self.muter("if v1:", "if v1 and not berry:")
        for porte, forme, attendu in ((banc.PORTE, "Yarn 1", FROZEN), (mutant, "Berry", IMMUTABLE)):
            rc, sortie = self.jouer(ENTETE_PRIO, porte)
            self.assertEqual(rc, 0, sortie)
            self.assertIn(f"yarn.lock de . : {forme} → yarn {' '.join(attendu)}", sortie)
            self.assertEqual(self.argv_yarn()[0], attendu, sortie)

    def test_V_BERRY(self):
        mutant = self.muter('startswith("__metadata:")', 'startswith("__metadata_:")')
        for porte, attendu in ((banc.PORTE, IMMUTABLE), (mutant, FROZEN)):
            rc, sortie = self.jouer(ENTETE_BERRY, porte)
            self.assertEqual(rc, 0, sortie)
            self.assertEqual(self.argv_yarn()[0], attendu, sortie)

    def test_V_OCTETS(self):
        mutant = self.muter("if apres is None or avant != apres:", "if False:")
        rc, sortie = self.jouer(ENTETE_BERRY, banc.PORTE, BANC_ECRIT_VERROU="# yarn lockfile v1\n")
        self.assertEqual(rc, 1, sortie)
        self.assertIn(REECRIT, sortie)
        self.assertIn(remede(self.tmp / "adoptant"), sortie)
        rc, sortie = self.jouer(ENTETE_BERRY, mutant, BANC_ECRIT_VERROU="# yarn lockfile v1\n")
        self.assertEqual(rc, 0, "le mutant V-OCTETS devait verdir un verrou réécrit : " + sortie)
        self.assertNotIn(REECRIT, sortie)

    def test_V_ORDRE(self):
        """Réserve T3 de la clôture : le contrôle d'octets replacé sous `rc == 0`
        réduit un verrou réécrit PUIS une install en échec au seul « a échoué »
        (le verrou réécrit est tu : un 2e passage verdirait)."""
        mutant = self.muter("if apres is None or avant != apres:",
                            "if rc == 0 and (apres is None or avant != apres):")
        env = {"BANC_ECRIT_VERROU": "# yarn lockfile v1\n", "BANC_RC_YARN": "1"}
        rc, sortie = self.jouer(ENTETE_BERRY, banc.PORTE, **env)
        self.assertEqual(rc, 1, sortie)
        self.assertIn(REECRIT, sortie)
        self.assertIn(remede(self.tmp / "adoptant") + AUSSI_RC1, sortie)
        rc, sortie = self.jouer(ENTETE_BERRY, mutant, **env)
        self.assertEqual(rc, 1, sortie)
        self.assertNotIn(REECRIT, sortie)
        self.assertIn(ECHOUE_RC1, sortie)

    def test_V_ILLISIBLE(self):
        mutant = self.muter("if avant is None:", "if False:")
        arbre = self.arbre_yarn(ENTETE_V1)
        self.rendre_illisible(arbre)
        rc, sortie, _res = self.lancer(arbre)
        self.assertEqual(rc, 1, sortie)
        self.assertIn(ILLISIBLE, sortie)
        rc, sortie, _res = self.lancer(arbre, porte=mutant)
        self.assertNotEqual(rc, 0, sortie)
        self.assertNotIn(ILLISIBLE, sortie)
        self.assertIn("TypeError", sortie)  # install_yarn(None, …), non rattrapée

    def test_V_UTF8(self):
        mutant = self.muter('octets[:4096].decode("utf-8", errors="replace")',
                            'octets[:4096].decode("utf-8")')
        arbre = self.arbre_coupe_utf8()
        rc, sortie, _res = self.lancer(arbre)
        self.assertEqual(rc, 0, sortie)
        self.assertIn(LIGNE_V1, sortie)
        rc, sortie, _res = self.lancer(arbre, porte=mutant)
        self.assertNotEqual(rc, 0, sortie)
        self.assertNotIn(LIGNE_V1, sortie)
        self.assertIn("UnicodeDecodeError", sortie)  # `main` n'a pas d'`except Exception`

    def test_X_STRIP(self):
        """Réserve C1 : l'en-tête v1 lu SANS `strip()` tombe en « en-tête non
        reconnu » — même argv (défaut de la table), seule la forme imprimée
        discrimine."""
        mutant = self.muter('ligne.strip() == "# yarn lockfile v1"', 'ligne == "# yarn lockfile v1"')
        rc, sortie = self.jouer(ENTETE_V1_BORDS, banc.PORTE)
        self.assertEqual(rc, 0, sortie)
        self.assertIn(LIGNE_V1, sortie)
        rc, sortie = self.jouer(ENTETE_V1_BORDS, mutant)
        self.assertEqual(rc, 0, sortie)
        self.assertNotIn(LIGNE_V1, sortie)
        self.assertIn(LIGNE_INCONNU, sortie)

    def test_K_BRANCHE_TOUS_VERROUS(self):
        """Constat de l'exec-critic (S-00004484) : la branche yarn ouverte à
        TOUT verrou, ses DEUX ancres mutées — `muter` n'en prend qu'une, la
        seconde est appliquée sur la copie qu'il rend. Sous le mutant, un verrou
        hors yarn à en-tête Berry imprime la ligne yarn et s'installe en
        --immutable, en VERT silencieux (ses octets ne bougent pas)."""
        mutant = self.muter('if fichier == "yarn.lock":', "if True:")
        ancre = 'if rang == 0 and fichier == "yarn.lock":'
        texte = mutant.read_text(encoding="utf-8")
        self.assertEqual(texte.count(ancre), 1, f"ancre du mutant introuvable : {ancre!r}")
        mutant.write_text(texte.replace(ancre, "if rang == 0:"), encoding="utf-8")
        for verrou, outil, install in VERROUS_HORS_YARN:
            with self.subTest(verrou=verrou):
                rc, sortie, _res = self.lancer(self.arbre_verrou(verrou, outil, ENTETE_BERRY))
                self.assertEqual(rc, 0, sortie)
                self.assertNotIn(TETE_YARN, sortie)
                self.assertEqual([a["argv"] for a in self.appels(outil)][:1], [install], sortie)
                rc, sortie, _res = self.lancer(self.arbre_verrou(verrou, outil, ENTETE_BERRY),
                                               porte=mutant)
                self.assertEqual(rc, 0, sortie)
                self.assertIn(LIGNE_BERRY, sortie)
                self.assertEqual([a["argv"] for a in self.appels(outil)][:1], [IMMUTABLE], sortie)


