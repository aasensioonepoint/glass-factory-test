"""Témoins et mutants YARN de la porte de l'ADOPTANT — T-00001189 (décision 3A).

POURQUOI UN FRÈRE : le banc principal, `test_porte_adoptant.py`, tient sous la
borne de 1600 lignes par fichier (convention python du kit) ; les témoins et
mutants neufs du choix de l'install yarn par l'EN-TÊTE du verrou vivent donc
ici (décision pilote decision/T-00001189/01), sur l'outillage du banc
principal : `_Banc` (arbre adoptant, bouchons, journal), `bouchon_source`,
`references_ancrees` et `MutantsDurablesTests.muter`.

RÈGLE D'IMPORT : toute sous-classe de unittest.TestCase importée par son nom
dans le frère est recollectée QUEL QUE SOIT son nom (mesuré) ; seules `_Banc`
(0 test) et des constantes s'importent ; A2 est le garde-fou (le compte de
`--collect-only` du plan). Tout le reste passe par le module (`banc.…`).

BOUCHON YARN (réserve C1) : le gabarit commun, plus une réécriture du
`yarn.lock` du cwd — SEULEMENT pour yarn et SEULEMENT sur `install` — quand
`BANC_ECRIT_VERROU` est posée (`@supprimer` le supprime). La réécriture précède
la sortie au rc `BANC_RC_YARN` du gabarit, comme Yarn 1 sauve le verrou AVANT
ses scripts. gitleaks, semgrep et npm restent sur le gabarit commun, intouchés.

SAUT ANNONCÉ, jamais un vert vide : chmod 000 n'interdit pas la lecture sous
root ni sous Windows (sonde de lecture). Le verrou à cheval sur la borne de
4096 octets s'écrit en OCTETS : aucune traduction de fins de ligne ne le déplace.
"""
from __future__ import annotations

import shlex
import shutil
import unittest
from pathlib import Path

import test_porte_adoptant as banc
from test_porte_adoptant import _Banc, MODULE_NPM

ENTETE_V1 = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n"
# Réserve C1 (X-STRIP) : l'en-tête v1 entouré d'espaces reste un v1.
ENTETE_V1_BORDS = ENTETE_V1.replace("# yarn lockfile v1", "  # yarn lockfile v1  ")
ENTETE_BERRY = ("# This file is generated by running \"yarn install\" inside your project.\n"
                "# Manual changes might be lost - proceed with caution!\n\n"
                "__metadata:\n  version: 8\n  cacheKey: 10c0\n")
# `__metadata:` PUIS `# yarn lockfile v1` : le v1 l'emporte quel que soit l'ordre.
ENTETE_PRIO = "__metadata:\n  version: 8\n# yarn lockfile v1\n"
LEURRE_INDENTE = "  __metadata:\n  version: 8\n"  # pas en colonne 0 : pas un Berry
FROZEN = ["install", "--frozen-lockfile"]
IMMUTABLE = ["install", "--immutable"]
LIGNE_V1 = "yarn.lock de . : Yarn 1 → yarn install --frozen-lockfile"
LIGNE_BERRY = "yarn.lock de . : Berry → yarn install --immutable"
LIGNE_INCONNU = "yarn.lock de . : en-tête non reconnu → yarn install --frozen-lockfile"
# Le ROUGE du verrou réécrit, coupé AVANT son remède `git -C <module> …` (chemin
# jetable) : chaque témoin de REECRIT asserte aussi `remede(arbre)`.
REECRIT = ("yarn install a modifié yarn.lock : module . (gestionnaire et verrou d'âges différents : "
           "nommez Yarn 2+ par le champ packageManager du package.json ; l'install a déjà réécrit "
           "yarn.lock : restaurez-le (")
AUSSI_RC1 = " ; l'install a AUSSI échoué (rc 1)"
ECHOUE_RC1 = "yarn install --immutable a échoué sur . (rc 1)"
ILLISIBLE = "yarn.lock illisible : module ."
SAUT_CHMOD = "SAUT ANNONCÉ : chmod 000 n'interdit pas la lecture ici (root ou Windows)"
# Les verrous HORS yarn de VERROUS_NPM (porte_adoptant.py), avec leur outil et
# leur install : la branche yarn (en-tête, contrôle d'octets) ne les voit pas.
VERROUS_HORS_YARN = (("pnpm-lock.yaml", "pnpm", FROZEN), ("package-lock.json", "npm", ["ci"]),
                     ("npm-shrinkwrap.json", "npm", ["ci"]))
TETE_YARN = "yarn.lock de "  # préfixe de la ligne imprimée par la seule branche yarn


def remede(arbre: Path) -> str:
    """La queue de REECRIT : le remède en `git -C <module>`, valable hors du cwd
    (le module est la racine de l'arbre ; chemins résolus des deux côtés)."""
    return f"git -C {shlex.quote(arbre.as_posix())} checkout -- yarn.lock))"


def bouchon_yarn_source() -> str:
    """Le gabarit commun de `banc.bouchon_source("yarn")`, plus la réécriture du
    verrou insérée AVANT son `sys.exit(`."""
    tete, sep, queue = banc.bouchon_source("yarn").rpartition("sys.exit(")
    if not sep:
        raise AssertionError("gabarit de bouchon sans `sys.exit(` : réécriture impossible")
    ajout = ("verrou = os.environ.get('BANC_ECRIT_VERROU')\n"
             "if verrou is not None and sys.argv[1:2] == ['install']:\n"
             "    if verrou == '@supprimer':\n"
             "        os.remove('yarn.lock')\n"
             "    else:\n"
             "        with open('yarn.lock', 'w', encoding='utf-8') as fh:\n"
             "            fh.write(verrou)\n")
    return tete + ajout + sep + queue


class _BancYarn(_Banc):
    """Outillage yarn commun aux témoins et aux mutants (0 test)."""

    def bouchon_yarn(self) -> None:
        chemin = self.bouchons / "yarn"
        chemin.write_text(bouchon_yarn_source(), encoding="utf-8")
        chemin.chmod(0o755)

    def arbre_yarn(self, contenu: str) -> Path:
        """Un adoptant NEUF dont la racine est un module npm à yarn.lock ;
        journal vidé, bouchons yarn (réécrivant) et npm posés."""
        arbre = self.tmp / "adoptant"
        if arbre.exists():
            shutil.rmtree(arbre)
        self.journal.unlink(missing_ok=True)
        self.bouchon_yarn()
        self.bouchon("npm")
        return self.adoptant({"package.json": MODULE_NPM["package.json"], "yarn.lock": contenu})

    def arbre_verrou(self, verrou: str, outil: str, contenu: str) -> Path:
        """Un adoptant NEUF dont la racine est un module npm au SEUL verrou
        `verrou` (aucun reste du sous-cas précédent) ; journal vidé, bouchon
        `outil` posé."""
        arbre = self.tmp / "adoptant"
        if arbre.exists():
            shutil.rmtree(arbre)
        self.journal.unlink(missing_ok=True)
        self.bouchon(outil)
        return self.adoptant({"package.json": MODULE_NPM["package.json"], verrou: contenu})

    def arbre_coupe_utf8(self) -> Path:
        """Un verrou v1 dont le « é » (2 octets) chevauche la borne de 4096 octets,
        réécrit en OCTETS après `arbre_yarn` (qui commite en créant l'arbre) :
        sous POSIX, les octets du commit ; ailleurs, aucune fin de ligne
        traduite. La porte ne sonde pas la propreté de la racine."""
        contenu = ENTETE_V1 + "#" * (4095 - len(ENTETE_V1.encode())) + "é\n"
        self.assertEqual(contenu.encode()[4095:4097], "é".encode())
        arbre = self.arbre_yarn(contenu)
        (arbre / "yarn.lock").write_bytes(contenu.encode("utf-8"))
        return arbre

    def rendre_illisible(self, arbre: Path) -> None:
        """chmod 000 du yarn.lock APRÈS le commit ; s'il se lit encore, saut annoncé."""
        verrou = arbre / "yarn.lock"
        verrou.chmod(0o000)
        self.addCleanup(verrou.chmod, 0o644)
        try:
            with open(verrou, "rb"):
                pass
        except OSError:
            return
        self.skipTest(SAUT_CHMOD)

    def argv_yarn(self) -> list[list[str]]:
        return [a["argv"] for a in self.appels("yarn")]


